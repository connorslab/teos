#!/usr/bin/env python3
"""Render both native configurations from one file; never start services."""
import argparse
import json
import os
from pathlib import Path
import re
import tempfile
import tomllib

MARKER = "# Generated by tools/configure.py; edit the shared source instead."
SCHEMA = {
    "network": None,
    "knots": {"host", "port", "cookie"},
    "listeners": {"bind"},
    "teos": {"api_port", "rpc_port", "internal_port", "max_registered_users",
             "subscription_slots", "subscription_duration", "renewal_slot_topups"},
    "lnd": {"enabled", "tower_port", "data_dir"},
}

class ConfigurationError(ValueError):
    pass

def integer(value, name, maximum=65535):
    if type(value) is not int or not 1 <= value <= maximum:
        raise ConfigurationError(f"{name} must be an integer between 1 and {maximum}")
    return value

def host(value, name):
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z0-9.-]+", value):
        raise ConfigurationError(f"{name} must be an IPv4 address or DNS hostname")
    return value

def render(config):
    if not isinstance(config, dict) or set(config) - SCHEMA.keys():
        raise ConfigurationError("Unknown top-level configuration setting")
    for section, allowed in SCHEMA.items():
        if allowed is not None:
            values = config.get(section, {})
            if not isinstance(values, dict) or set(values) - allowed:
                raise ConfigurationError(f"Unknown or invalid {section} settings")
    network = config.get("network", "mainnet")
    if network not in ("mainnet", "regtest"):
        raise ConfigurationError("network must be mainnet or regtest")
    knots = config.get("knots", {})
    rpc_host = host(knots.get("host", "127.0.0.1"), "knots.host")
    rpc_port = integer(knots.get("port", 8332 if network == "mainnet" else 18443), "knots.port")
    cookie = knots.get("cookie")
    # Native INI and TOML must interpret the same literal path.
    if not isinstance(cookie, str) or not cookie.startswith("/") or any(
        c in cookie for c in '\r\n\x00#;"\\'
    ) or cookie != cookie.strip():
        raise ConfigurationError("knots.cookie must be an absolute POSIX path without control characters, quotes, backslashes, # or ;")
    bind = host(config.get("listeners", {}).get("bind", "127.0.0.1"), "listeners.bind")
    teos, lnd = config.get("teos", {}), config.get("lnd", {})
    enabled = lnd.get("enabled", False)
    if type(enabled) is not bool:
        raise ConfigurationError("lnd.enabled must be a boolean")
    ports = {}
    for section, values, defaults in (
        ("teos", teos, {"api_port":9814, "rpc_port":8814, "internal_port":50051}),
        ("lnd", lnd, {"tower_port":9911}),
    ):
        for key, default in defaults.items():
            ports[f"{section}.{key}"] = integer(values.get(key, default), f"{section}.{key}")
    active_ports = [value for key, value in ports.items() if enabled or key.startswith("teos.")]
    if len(set(active_ports)) != len(active_ports) or rpc_port in active_ports:
        raise ConfigurationError("Listener ports must be distinct and must not collide with Knots RPC")
    count = integer(teos.get("max_registered_users", 100), "teos.max_registered_users", 1000000)
    slots = integer(teos.get("subscription_slots", 10000), "teos.subscription_slots", 100000000)
    duration = integer(teos.get("subscription_duration", 4320), "teos.subscription_duration", 10000000)
    topups = teos.get("renewal_slot_topups", False)
    if type(topups) is not bool:
        raise ConfigurationError("teos.renewal_slot_topups must be a boolean")
    q = json.dumps
    rust = f'''{MARKER}
btc_network = {q(network)}
btc_rpc_connect = {q(rpc_host)}
btc_rpc_port = {rpc_port}
btc_rpc_cookie = {q(cookie)}
api_bind = {q(bind)}
api_port = {ports["teos.api_port"]}
rpc_bind = "127.0.0.1"
rpc_port = {ports["teos.rpc_port"]}
internal_api_bind = "127.0.0.1"
internal_api_port = {ports["teos.internal_port"]}
force_update = false
max_registered_users = {count}
subscription_slots = {slots}
subscription_duration = {duration}
renewal_slot_topups = {str(topups).lower()}
'''
    data_dir = lnd.get("data_dir", "/var/lib/teos-lnd")
    if not isinstance(data_dir, str) or not data_dir.startswith("/"):
        raise ConfigurationError("lnd.data_dir must be an absolute POSIX path")
    native = json.dumps({"_generated": MARKER, "network": network, "rpc_url": f"http://{rpc_host}:{rpc_port}",
                         "cookie": cookie, "listen": f"{bind}:{ports['lnd.tower_port']}",
                         "data_dir": data_dir}, indent=2) + "\n"
    result = {"teos/teos.toml": rust}
    if enabled:
        result["lnd/tower.json"] = native
    return result

def is_generated(path):
    text = path.read_text()
    if path.name == "tower.json":
        try:
            return json.loads(text).get("_generated") == MARKER
        except (ValueError, AttributeError):
            return False
    return text.startswith(MARKER + "\n")

def write_configs(output, contents, overwrite=False):
    output = Path(output).absolute()
    # Check all destinations before writing either file. Refuse symlink traversal.
    for rel in contents:
        target = output / rel
        if any(p.is_symlink() for p in [target, *target.parents]):
            raise ConfigurationError("Output paths must not contain symbolic links")
        if target.exists():
            if not overwrite or not target.is_file() or not is_generated(target):
                raise ConfigurationError("Existing configuration refused; --overwrite applies only to generated files")
    for rel, content in contents.items():
        target = output / rel
        target.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
        fd, temp = tempfile.mkstemp(prefix=".config-", dir=target.parent)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temp, target)
        finally:
            if os.path.exists(temp):
                os.unlink(temp)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path)
    parser.add_argument("--output", type=Path, default=Path("generated"))
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--check", action="store_true", help="Validate without writing")
    args = parser.parse_args()
    try:
        with args.config.open("rb") as stream:
            contents = render(tomllib.load(stream))
        if not args.check:
            write_configs(args.output, contents, args.overwrite)
    except ConfigurationError as exc:
        parser.exit(1, f"Configuration failed: {exc}\n")
    except (ValueError, OSError) as exc:
        # Do not echo configuration contents or credentials.
        parser.exit(1, f"Configuration failed: {type(exc).__name__}. Check settings and output permissions.\n")
    print("Configuration valid." if args.check else "Generated " + ", ".join(contents) + ". No services restarted.")

if __name__ == "__main__":
    main()
